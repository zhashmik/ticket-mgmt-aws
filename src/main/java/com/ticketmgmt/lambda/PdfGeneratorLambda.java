package com.ticketmgmt.lambda;

import com.amazonaws.services.lambda.runtime.Context;
import com.amazonaws.services.lambda.runtime.RequestHandler;
import com.amazonaws.services.lambda.runtime.events.SNSEvent;
import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;
import com.itextpdf.kernel.colors.ColorConstants;
import com.itextpdf.kernel.pdf.PdfDocument;
import com.itextpdf.kernel.pdf.PdfWriter;
import com.itextpdf.layout.Document;
import com.itextpdf.layout.element.Cell;
import com.itextpdf.layout.element.Paragraph;
import com.itextpdf.layout.element.Table;
import com.itextpdf.layout.properties.TextAlignment;
import com.itextpdf.layout.properties.UnitValue;
import software.amazon.awssdk.core.sync.RequestBody;
import software.amazon.awssdk.services.s3.S3Client;
import software.amazon.awssdk.services.s3.model.PutObjectRequest;
import software.amazon.awssdk.services.s3.model.ServerSideEncryption;

import java.io.ByteArrayOutputStream;
import java.time.LocalDateTime;
import java.time.format.DateTimeFormatter;

public class PdfGeneratorLambda implements RequestHandler<SNSEvent, String> {

    private static final ObjectMapper mapper = new ObjectMapper();
    private static final S3Client s3 = S3Client.create();
    private static final String BUCKET = System.getenv("S3_BUCKET_NAME");

    @Override
    public String handleRequest(SNSEvent event, Context ctx) {
        for (SNSEvent.SNSRecord rec : event.getRecords()) {
            try {
                JsonNode node = mapper.readTree(rec.getSNS().getMessage());
                if (!"TICKET_RESOLVED".equals(node.get("eventType").asText())) continue;

                long id = node.get("ticketId").asLong();
                byte[] pdf = generatePdf(id, node.get("title").asText(),
                    node.get("status").asText(), node.get("priority").asText(),
                    node.get("createdBy").asText());

                String key = String.format("generated-pdfs/%d/resolution-%d.pdf", id, System.currentTimeMillis());
                s3.putObject(PutObjectRequest.builder().bucket(BUCKET).key(key)
                    .contentType("application/pdf")
                    .serverSideEncryption(ServerSideEncryption.AWS_KMS).build(),
                    RequestBody.fromBytes(pdf));
                ctx.getLogger().log("PDF uploaded: " + key);
            } catch (Exception e) {
                ctx.getLogger().log("ERROR: " + e.getMessage());
                throw new RuntimeException(e);
            }
        }
        return "OK";
    }

    private byte[] generatePdf(long id, String title, String status,
            String priority, String createdBy) throws Exception {
        ByteArrayOutputStream baos = new ByteArrayOutputStream();
        PdfDocument pdfDoc = new PdfDocument(new PdfWriter(baos));
        Document doc = new Document(pdfDoc);

        doc.add(new Paragraph("IT Ticket Resolution Report").setFontSize(22).setBold()
            .setTextAlignment(TextAlignment.CENTER).setFontColor(ColorConstants.DARK_GRAY));
        doc.add(new Paragraph("Generated: " + LocalDateTime.now()
            .format(DateTimeFormatter.ofPattern("yyyy-MM-dd HH:mm:ss")))
            .setTextAlignment(TextAlignment.CENTER).setFontColor(ColorConstants.GRAY));
        doc.add(new Paragraph("\n"));

        Table table = new Table(UnitValue.createPercentArray(new float[]{30, 70})).useAllAvailableWidth();
        addRow(table, "Ticket ID", "#" + id);
        addRow(table, "Title", title);
        addRow(table, "Status", status);
        addRow(table, "Priority", priority);
        addRow(table, "Raised By", createdBy);
        addRow(table, "Resolution Date", LocalDateTime.now().format(DateTimeFormatter.ISO_LOCAL_DATE));
        doc.add(table);

        doc.add(new Paragraph("\n\nAuto-generated by IT Ticket Management System.")
            .setFontSize(9).setFontColor(ColorConstants.GRAY).setTextAlignment(TextAlignment.CENTER));
        doc.close();
        return baos.toByteArray();
    }

    private void addRow(Table t, String label, String value) {
        t.addCell(new Cell().add(new Paragraph(label).setBold())
            .setBackgroundColor(ColorConstants.LIGHT_GRAY).setPadding(8));
        t.addCell(new Cell().add(new Paragraph(value)).setPadding(8));
    }
}
